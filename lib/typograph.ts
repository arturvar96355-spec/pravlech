const NBSP = ' ';

// Предлоги и союзы из 1–2 букв: после них пробел неразрывный.
const SHORT_WORDS =
  'а|б|в|и|к|о|с|у|я|бы|во|да|до|за|из|ко|на|не|ни|но|об|от|по|со|то|же|ли|ль|ну';

const UNITS = '₽|руб\\.|мин|мин\\.|ч|км|мг|мл|шт\\.?|%|лет|года|год|дн\\.|дней|оценок|отзывов|упоминаний';

/**
 * Типографика для текстов из /content:
 * неразрывные пробелы, «ёлочки», длинное тире, ₽ после числа.
 */
export function typograph(input: string): string {
  let s = input;

  // "кавычки" → «ёлочки» (только прямые парные)
  s = s.replace(/"([^"]*)"/g, '«$1»');

  // дефис/короткое тире с пробелами → длинное тире с неразрывным пробелом перед ним
  s = s.replace(/\s+[-–]\s+/g, `${NBSP}— `);
  s = s.replace(/\s+—\s+/g, `${NBSP}— `);

  // предлоги и союзы из 1–2 букв
  const short = new RegExp(`(^|[\\s«(\\u00A0])(${SHORT_WORDS}) `, 'gi');
  // два прохода — на случай "в к" подряд
  s = s.replace(short, `$1$2${NBSP}`).replace(short, `$1$2${NBSP}`);

  // число + единица
  s = s.replace(new RegExp(`(\\d) (${UNITS})`, 'g'), `$1${NBSP}$2`);

  // группы разрядов: "3 500" → "3 500"
  s = s.replace(/(\d) (\d{3})(?!\d)/g, `$1${NBSP}$2`);

  // ₽ после числа: "₽ 3500" → "3500 ₽"
  s = s.replace(/₽\s*(\d[\d  ]*)/g, `$1${NBSP}₽`);

  // 24/7, 8:00–21:00: тире между цифрами — без пробелов
  return s;
}

export const tp = typograph;

/** 3500 → «3 500 ₽» (неразрывные пробелы). */
export function formatPrice(value: number): string {
  return `${Math.round(value).toString().replace(/\B(?=(\d{3})+(?!\d))/g, NBSP)}${NBSP}₽`;
}
