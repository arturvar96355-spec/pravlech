/** Топ-позиции для блока на главной */
export const topPriceIds = ['therapy-0', 'cardio-0', 'us-25', 'cardio-5'] as const;

export const allPriceItems: Array<PriceItem & { group: string }> = priceGroups.flatMap((g) =>
  g.items.map((i) => ({ ...i, group: g.title })),
);

/** Позиции, у которых одинаковые названия внутри разных групп, различаем по группе при показе. */
export function topItems() {
  return topPriceIds.map((id) => allPriceItems.find((i) => i.id === id)!);
}

export function getPriceGroup(id: string) {
  return priceGroups.find((g) => g.id === id);
}
