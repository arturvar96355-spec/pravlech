export type PriceItem = {
  id: string;
  title: string;
  /** точная цена */
  price?: number;
  /** «от …» */
  from?: boolean;
  /** «по запросу» */
  onRequest?: boolean;
  note?: string;
  /** на позицию действует выходная скидка */
  weekendDiscount?: boolean;
  /** заглушка вместо цены */
  todo?: string;
};

export type PriceGroup = { id: string; title: string; source?: string; items: PriceItem[] };

/** [название, цена, флаг]: 'от' — «от …», 'зап' — по запросу */
type Row = [title: string, price: number | null, flag?: 'от' | 'зап'];

function group(id: string, title: string, rows: Row[], source?: string): PriceGroup {
  return {
    id,
    title,
    source,
    items: rows.map(([t, price, flag], i) => ({
      id: `${id}-${i}`,
      title: t,
      price: price ?? undefined,
      from: flag === 'от' || undefined,
      onRequest: flag === 'зап' || undefined,
    })),
  };
}

